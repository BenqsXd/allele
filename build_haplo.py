"""Build haplo.js: reference data for mtDNA and Y-chromosome haplogroups from CRAM reads.

Usage: python build_haplo.py [--refresh]

Sources
  mtDNA  PhyloTree build 17, rCRS-rooted, as distributed by HaploGrep (github.com/genepi/phylotree-rcrs-17, MIT)
         with HaploGrep's per-position phylogenetic weights, and the rCRS sequence (NC_012920).
  Y      ISOGG Y-DNA SNP index 2016 as distributed with 23andMe yhaplo (github.com/23andMe/yhaplo);
         reference bases at each position from UCSC hg19 chrY (identical to GRCh37 Y).
"""
import gzip, json, os, re, subprocess, sys, urllib.request, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(HERE, "haplo.js")
REFRESH = "--refresh" in sys.argv


def get(url, name):
    path = os.path.join(DATA, name)
    if REFRESH or not os.path.exists(path):
        print("downloading", url)
        urllib.request.urlretrieve(url, path)
    return path


def mt():
    repo = os.path.join(DATA, "phylotree-rcrs-17")
    if REFRESH or not os.path.exists(repo):
        subprocess.run(["git", "clone", "-q", "--depth", "1", "https://github.com/genepi/phylotree-rcrs-17", repo], check=True)
    ref = "".join(l.strip() for l in open(os.path.join(repo, "src", "rcrs.fasta")) if not l.startswith(">")).upper()
    assert len(ref) == 16569, len(ref)
    root = ET.parse(os.path.join(repo, "src", "tree.xml")).getroot()
    nodes = []

    def walk(el, parent):
        for hg in el.findall("haplogroup"):
            polys = [p.text.strip() for p in hg.findall("details/poly") if p.text]
            # keep substitutions only (e.g. 15314A, 16519C!); indels (315.1C, 523d) are not called from reads here
            subs = []
            for p in polys:
                m = re.fullmatch(r"(\d+)([ACGT])(!*)", p)
                if m:
                    subs.append(f"{m.group(1)}{m.group(2)}{m.group(3)}")
            nodes.append([hg.get("name"), parent, " ".join(subs)])
            walk(hg, len(nodes) - 1)

    walk(root, -1)
    weights = {}
    for line in open(os.path.join(repo, "src", "weights.txt")):
        parts = line.split()
        if len(parts) >= 2:
            m = re.fullmatch(r"(\d+)([ACGT])", parts[0])
            if m:
                try:
                    weights[m.group(1) + m.group(2)] = round(float(parts[1]), 2)
                except ValueError:
                    pass
    print(f"mtDNA: {len(nodes)} haplogroups, {len(weights)} weights")
    return ref, nodes, weights


def y():
    isogg = get("https://raw.githubusercontent.com/23andMe/yhaplo/master/yhaplo/data/variants/isogg.2016.01.04.txt", "isogg.2016.01.04.txt")
    fa = get("https://hgdownload.soe.ucsc.edu/goldenPath/hg19/chromosomes/chrY.fa.gz", "hg19_chrY.fa.gz")
    seq = "".join(l.strip() for l in gzip.open(fa, "rt") if not l.startswith(">")).upper()
    snps, seen = [], set()
    for line in open(isogg, encoding="utf-8", errors="replace").readlines()[1:]:
        cols = [c.strip() for c in line.split("\t")]
        if len(cols) < 6:
            continue
        name, hap, _, _, pos, mut = cols[:6]
        hap = hap.replace("(Notes)", "").strip()
        m = re.fullmatch(r"([ACGT])->([ACGT])", mut)
        if not m or not pos.isdigit() or not re.fullmatch(r"[A-T][0-9a-z]*", hap):
            continue
        p = int(pos)
        anc, der = m.group(1), m.group(2)
        ref = seq[p - 1]
        if ref not in (anc, der) or p in seen:
            continue  # reference disagrees with the record, or a second name for the same site
        seen.add(p)
        snps.append([p, anc, der, hap, name.split(".")[0], ref])
    snps.sort()
    print(f"Y: {len(snps)} SNPs")
    return snps


def main():
    os.makedirs(DATA, exist_ok=True)
    ref, nodes, weights = mt()
    ysnps = y()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build_haplo.py. mtDNA: PhyloTree 17 (rCRS-rooted, HaploGrep, MIT). Y: ISOGG 2016 SNP index via yhaplo. Do not edit.\n")
        f.write("const MT_REF=" + json.dumps(ref) + ";\n")
        f.write("const MT_TREE=" + json.dumps(nodes, separators=(",", ":")) + ";\n")
        f.write("const MT_WEIGHTS=" + json.dumps(weights, separators=(",", ":")) + ";\n")
        f.write("const Y_SNPS=" + json.dumps(ysnps, separators=(",", ":")) + ";\n")
    print(f"-> {OUT} ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    main()
