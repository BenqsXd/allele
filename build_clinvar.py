"""Build clinvar.js for the DNA analyzer from NCBI ClinVar.

Usage:
    python build_clinvar.py            # downloads data/variant_summary.txt.gz if missing
    python build_clinvar.py --refresh  # force a fresh download

Keeps GRCh37 single-nucleotide variants with an rsID that ClinVar classifies as
pathogenic / likely pathogenic (>=1 review star), risk factor, protective or drug response.
Adds each gene's mode of inheritance from GenCC (thegencc.org, CC0), curations rated Moderate or stronger.
"""
import gzip, json, os, sys, time, urllib.request

URL = "https://ftp.ncbi.nlm.nih.gov/pub/clinvar/tab_delimited/variant_summary.txt.gz"
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "data", "variant_summary.txt.gz")
OUT = os.path.join(HERE, "clinvar.js")
GENCC_URL = "https://search.thegencc.org/download/action/submissions-export-tsv"
GENCC = os.path.join(HERE, "data", "gencc-submissions.tsv")
MOI = {"Autosomal recessive": "AR", "Autosomal dominant": "AD", "Semidominant": "AD", "X-linked recessive": "XL",
       "X-linked": "XL", "X-linked dominant": "XLD", "Y-linked inheritance": "YL", "Mitochondrial": "MT"}


def gene_moi():
    """Gene -> modes of inheritance with at least Moderate GenCC evidence, e.g. "AR" or "AD/AR"."""
    import csv
    csv.field_size_limit(10**8)
    out = {}
    with open(GENCC, encoding="utf-8", errors="replace") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r.get("classification_title") not in ("Definitive", "Strong", "Moderate"):
                continue
            m = MOI.get((r.get("moi_title") or "").strip())
            if m:
                out.setdefault(r["gene_symbol"], set()).add(m)
    return {g: "/".join(sorted(v)) for g, v in out.items()}

STARS = {
    "practice guideline": 4,
    "reviewed by expert panel": 3,
    "criteria provided, multiple submitters, no conflicts": 2,
    "criteria provided, single submitter": 1,
    "criteria provided, conflicting classifications": 1,
}


def sig_code(sig):
    s = sig.lower()
    if s.startswith("conflicting") or "benign" in s or "uncertain" in s:
        return None
    if "pathogenic" in s:
        return "LP" if s.startswith("likely pathogenic") else "P"
    for word, code in (("drug response", "DR"), ("risk factor", "RF"), ("protective", "PR")):
        if word in s:
            return code
    return None


def build():
    out, n = {}, 0
    with gzip.open(SRC, "rt", encoding="utf-8", errors="replace") as f:
        cols = f.readline().lstrip("#").rstrip("\n").split("\t")
        ix = {c: i for i, c in enumerate(cols)}
        for line in f:
            r = line.rstrip("\n").split("\t")
            if r[ix["Assembly"]] != "GRCh37" or r[ix["Type"]] != "single nucleotide variant":
                continue
            rs = r[ix["RS# (dbSNP)"]]
            if rs in ("-1", "", "-"):
                continue
            code = sig_code(r[ix["ClinicalSignificance"]])
            if not code:
                continue
            stars = STARS.get(r[ix["ReviewStatus"]], 0)
            if code in ("P", "LP") and stars < 1:
                continue
            ref, alt = r[ix["ReferenceAlleleVCF"]], r[ix["AlternateAlleleVCF"]]
            if len(ref) != 1 or len(alt) != 1 or ref == alt:
                continue
            conds = [c for c in r[ix["PhenotypeList"]].split("|") if c not in ("not provided", "not specified", "See cases")]
            cond = "; ".join(dict.fromkeys(conds))[:160] or "condition not specified"
            out.setdefault("rs" + rs, []).append(
                [r[ix["GeneSymbol"]].split(";")[0], code, cond, ref, alt, stars, int(r[ix["VariationID"]])])
            n += 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build_clinvar.py from NCBI ClinVar variant_summary (GRCh37). Do not edit.\n")
        f.write("const CLINVAR_DATE=%s;\n" % json.dumps(time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(SRC)))))
        moi = gene_moi()
        genes = {rec[0] for recs in out.values() for rec in recs}
        f.write("const GENE_MOI=" + json.dumps({g: m for g, m in sorted(moi.items()) if g in genes}, separators=(",", ":")) + ";\n")
        f.write("const CLINVAR=")
        json.dump(out, f, separators=(",", ":"))
        f.write(";\n")
    print(f"{n} variants, {len(out)} rsIDs -> {OUT} ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    if "--refresh" in sys.argv or not os.path.exists(SRC):
        os.makedirs(os.path.dirname(SRC), exist_ok=True)
        print("Downloading", URL)
        urllib.request.urlretrieve(URL, SRC)
    if "--refresh" in sys.argv or not os.path.exists(GENCC):
        print("Downloading", GENCC_URL)
        urllib.request.urlretrieve(GENCC_URL, GENCC)
    build()
